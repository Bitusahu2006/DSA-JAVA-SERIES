public class SolidRectangular {
    public static void main(String args[]){
        int n=3;

        for(int row=1; row<=n;row++){
            // for each row -> 5 columns
            for(int col=1; col<=5; col++){
                // star
                System.out.print("* ");

            }
            System.out.println();

        }
    }
}
